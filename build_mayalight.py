"""Builds Mayalight_stylesheet.qss from one palette.

Run outside Maya:  python build_mayalight.py
Change a shade below, run again, then re-pick "Maya Light" in the Themes menu.
"""
import os

# ---------------- Palette (r, g, b) ----------------
PANEL = (212, 212, 212)        # panels, dialogs, menus: the classic light grey
CHROME = (163, 163, 163)       # icon bars and icon buttons: old Maya viewport grey,
                               # kept darker so Maya's light icons stay visible
CHROME_HOVER = (190, 190, 190)
CHROME_DOWN = (120, 120, 120)
INSET = (196, 196, 196)        # Outliner and other lists
FIELD = (255, 255, 255)        # text and number fields
TEXT = (0, 0, 0)
TEXT_OFF = (120, 120, 120)     # disabled text
EDGE = (110, 110, 110)         # dark borders
EDGE_SOFT = (150, 150, 150)
BTN_TOP = (244, 244, 244)      # raised buttons, top of gradient
BTN_BOTTOM = (214, 214, 214)
BTN_DOWN = (184, 184, 184)
TAB_OFF = (190, 190, 190)      # unselected tabs
HILITE = (49, 106, 197)        # selection blue
HILITE_TEXT = (255, 255, 255)
HOVER = (224, 232, 246)        # list row hover
SCRIPT_BG = (43, 43, 43)       # Script Editor stays dark: Maya's syntax colours assume it
SCRIPT_TEXT = (220, 220, 220)
TIP = (255, 255, 225)          # tooltip yellow

# Bars that hold light-on-dark icons. Everything inside them takes CHROME.
CHROME_BARS = [
    "StatusLine", "MainStatusLineLayout",
    "Shelf", "ShelfLayout", "MainShelfLayout",
    "ToolBox", "MainToolboxLayout",
    "modelEditorIconBar",
    "TimeSlider", "RangeSlider", "MainTimeSliderLayout", "MainPlaybackRangeLayout",
]

# Maya's icon-only buttons, matched by the start of their object name.
ICON_BUTTONS = ["shelfButton", "iconTextButton", "symbolButton", "symbolCheckBox", "quickLayout"]


def c(rgb):
    return "rgb(%d,%d,%d)" % rgb


def header(name):
    return "/*-----%s%s*/" % (name, "-" * 140)


def bars(suffix):
    return ",\n".join("#%s%s" % (b, suffix) for b in CHROME_BARS)


def icon_buttons(suffix=""):
    return ",\n".join('QPushButton[objectName^="%s"]%s' % (n, suffix) for n in ICON_BUTTONS)


P = dict(
    panel=c(PANEL), chrome=c(CHROME), chrome_hover=c(CHROME_HOVER), chrome_down=c(CHROME_DOWN),
    inset=c(INSET), field=c(FIELD), text=c(TEXT), text_off=c(TEXT_OFF), edge=c(EDGE),
    edge_soft=c(EDGE_SOFT), btn_top=c(BTN_TOP), btn_bottom=c(BTN_BOTTOM), btn_down=c(BTN_DOWN),
    tab_off=c(TAB_OFF), hilite=c(HILITE), hilite_text=c(HILITE_TEXT), hover=c(HOVER),
    script_bg=c(SCRIPT_BG), script_text=c(SCRIPT_TEXT), tip=c(TIP),
)
P["raised"] = "qlineargradient(x1:0, y1:0, x2:0, y2:1, stop:0 %s, stop:1 %s)" % (c(BTN_TOP), c(BTN_BOTTOM))

SECTIONS = []


def add(name, body):
    SECTIONS.append(header(name) + "\n" + body.strip() % P)


add("Maya Light (2010 style)", """
/* Generated by build_mayalight.py. Edit the palette there rather than this file. */
""")

add("QWidget", """
QWidget { background-color: %(panel)s; color: %(text)s; selection-color: %(hilite_text)s; selection-background-color: %(hilite)s; }

QWidget:disabled { color: %(text_off)s; }
""")

add("QLabel", """
QLabel { background-color: transparent; color: %(text)s; }

QLabel:disabled { color: %(text_off)s; }
""")

add("QMenuBar", """
QMenuBar { background-color: %(panel)s; spacing: 2px; }

QMenuBar::item { background-color: transparent; color: %(text)s; padding: 2px 6px 2px 6px; }

QMenuBar::item:selected { background-color: %(hilite)s; color: %(hilite_text)s; }

QMenuBar::item:pressed { background-color: %(hilite)s; color: %(hilite_text)s; }
""")

add("QMenu", """
QMenu { background-color: %(panel)s; color: %(text)s; border: 1px solid %(edge)s; }

QMenu::item { background-color: transparent; padding: 3px 20px 3px 20px; }

QMenu::item:selected { background-color: %(hilite)s; color: %(hilite_text)s; }

QMenu::item:disabled { color: %(text_off)s; }

QMenu::item:disabled:selected { background-color: transparent; color: %(text_off)s; }

QMenu::separator { height: 1px; background-color: %(edge_soft)s; margin: 3px 4px 3px 4px; }

QMenu::tearoff { height: 6px; background-color: %(tab_off)s; border-bottom: 1px solid %(edge_soft)s; }

QMenu::tearoff:selected { background-color: %(hilite)s; }

QMenu QLabel, QMenu QWidget { background-color: %(panel)s; color: %(text)s; }
""")

add("QPushButton", """
QPushButton { color: %(text)s; background-color: %(raised)s; border: 1px solid %(edge)s; border-radius: 2px; padding: 1px 6px 1px 6px; }

QPushButton:hover { background-color: %(btn_top)s; }

QPushButton:pressed { background-color: %(btn_down)s; }

QPushButton:checked { background-color: %(btn_down)s; }

QPushButton:default { border: 2px solid %(hilite)s; }

QPushButton:disabled { background-color: %(panel)s; color: %(text_off)s; border-color: %(edge_soft)s; }

QPushButton:flat { background-color: transparent; border: none; }
""")

add("Icon buttons", """
/* Maya's icons are drawn for a dark UI, so icon-only buttons sit on the darker grey. */
""" + icon_buttons() + """,
QToolButton { background-color: %(chrome)s; border: none; border-radius: 2px; padding: 0px; }

""" + icon_buttons(":hover") + """,
QToolButton:hover { background-color: %(chrome_hover)s; }

""" + icon_buttons(":pressed") + """,
""" + icon_buttons(":checked") + """,
QToolButton:pressed,
QToolButton:checked { background-color: %(chrome_down)s; }
""")

add("QLineEdit", """
QLineEdit { color: %(text)s; background-color: %(field)s; border: 1px solid %(edge_soft)s; border-top-color: %(edge)s; border-left-color: %(edge)s; padding: 0px 2px 0px 2px; }

QLineEdit:focus { border-color: %(hilite)s; }

QLineEdit:read-only { background-color: %(inset)s; }

QLineEdit:disabled { color: %(text_off)s; background-color: %(panel)s; }
""")

add("QSpinBox", """
QSpinBox, QDoubleSpinBox { color: %(text)s; background-color: %(field)s; border: 1px solid %(edge_soft)s; border-top-color: %(edge)s; border-left-color: %(edge)s; }

QSpinBox:disabled, QDoubleSpinBox:disabled { color: %(text_off)s; background-color: %(panel)s; }
""")

add("QComboBox", """
QComboBox { color: %(text)s; background-color: %(raised)s; border: 1px solid %(edge)s; border-radius: 2px; padding-left: 6px; }

QComboBox:on { background-color: %(btn_down)s; }

QComboBox:disabled { color: %(text_off)s; background-color: %(panel)s; border-color: %(edge_soft)s; }

QComboBox QAbstractItemView { color: %(text)s; background-color: %(field)s; border: 1px solid %(edge)s; selection-color: %(hilite_text)s; selection-background-color: %(hilite)s; }
""")

add("QCheckBox", """
QCheckBox { background-color: transparent; color: %(text)s; }

QCheckBox:disabled { color: %(text_off)s; }

QCheckBox::indicator { width: 11px; height: 11px; border: 1px solid %(edge)s; background-color: %(field)s; }

QCheckBox::indicator:hover { border-color: %(hilite)s; }

QCheckBox::indicator:checked { background-color: %(hilite)s; border: 3px solid %(field)s; width: 7px; height: 7px; }

QCheckBox::indicator:indeterminate { background-color: %(edge_soft)s; border: 3px solid %(field)s; width: 7px; height: 7px; }

QCheckBox::indicator:disabled { background-color: %(panel)s; border-color: %(edge_soft)s; }

QCheckBox::indicator:checked:disabled { background-color: %(text_off)s; border: 3px solid %(panel)s; }
""")

add("QRadioButton", """
QRadioButton { background-color: transparent; color: %(text)s; }

QRadioButton:disabled { color: %(text_off)s; }

QRadioButton::indicator { width: 11px; height: 11px; border: 1px solid %(edge)s; border-radius: 6px; background-color: %(field)s; }

QRadioButton::indicator:hover { border-color: %(hilite)s; }

QRadioButton::indicator:checked { background-color: %(hilite)s; border: 3px solid %(field)s; border-radius: 6px; width: 7px; height: 7px; }

QRadioButton::indicator:disabled { background-color: %(panel)s; border-color: %(edge_soft)s; }
""")

add("QSlider", """
QSlider { background-color: transparent; }

QSlider::groove:horizontal { height: 4px; background-color: %(inset)s; border: 1px solid %(edge)s; }

QSlider::sub-page:horizontal { background-color: %(edge_soft)s; border: 1px solid %(edge)s; }

QSlider::handle:horizontal { width: 7px; margin: -6px 0px -6px 0px; background-color: %(raised)s; border: 1px solid %(edge)s; border-radius: 1px; }

QSlider::handle:horizontal:hover { background-color: %(btn_top)s; border-color: %(hilite)s; }

QSlider::handle:horizontal:disabled { background-color: %(panel)s; border-color: %(edge_soft)s; }

QSlider::groove:vertical { width: 4px; background-color: %(inset)s; border: 1px solid %(edge)s; }

QSlider::handle:vertical { height: 7px; margin: 0px -6px 0px -6px; background-color: %(raised)s; border: 1px solid %(edge)s; border-radius: 1px; }
""")

add("QScrollBar", """
QScrollBar:vertical { border: 0px; background-color: %(inset)s; width: 14px; margin: 0px; }

QScrollBar:horizontal { border: 0px; background-color: %(inset)s; height: 14px; margin: 0px; }

QScrollBar::handle:vertical { min-height: 24px; background-color: %(btn_bottom)s; border: 1px solid %(edge)s; margin: 1px; border-radius: 2px; }

QScrollBar::handle:horizontal { min-width: 24px; background-color: %(btn_bottom)s; border: 1px solid %(edge)s; margin: 1px; border-radius: 2px; }

QScrollBar::handle:vertical:hover, QScrollBar::handle:horizontal:hover { background-color: %(btn_top)s; }

QScrollBar::add-line:vertical, QScrollBar::sub-line:vertical { height: 0px; }

QScrollBar::add-line:horizontal, QScrollBar::sub-line:horizontal { width: 0px; }

QScrollBar::add-page, QScrollBar::sub-page { background-color: transparent; }
""")

add("QTabBar", """
QTabBar { background-color: transparent; }

QTabBar::tab { color: %(text)s; background-color: %(tab_off)s; border: 1px solid %(edge)s; padding: 3px 9px 3px 9px; border-top-left-radius: 3px; border-top-right-radius: 3px; }

QTabBar::tab:selected { background-color: %(panel)s; border-bottom-color: %(panel)s; }

QTabBar::tab:!selected { margin-top: 2px; }

QTabBar::tab:hover:!selected { background-color: %(btn_bottom)s; }

QTabBar::tab:disabled { color: %(text_off)s; }
""")

add("QTabWidget", """
QTabWidget { border: none; }

QTabWidget::pane { background-color: %(panel)s; border-top: 1px solid %(edge)s; }
""")

add("QTreeView / QListView", """
QTreeView, QListView { color: %(text)s; background-color: %(inset)s; alternate-background-color: %(inset)s; border: 1px solid %(edge_soft)s; }

QTreeView:disabled, QListView:disabled { color: %(text_off)s; }

QTreeView::item:hover, QListView::item:hover { background-color: %(hover)s; color: %(text)s; }

QTreeView::item:selected, QListView::item:selected { background-color: %(hilite)s; color: %(hilite_text)s; }

QTreeView::item:disabled, QListView::item:disabled { color: %(text_off)s; }
""")

add("QTableView", """
QTableView { color: %(text)s; background-color: %(field)s; alternate-background-color: %(panel)s; gridline-color: %(edge_soft)s; border: 1px solid %(edge_soft)s; }

QTableView QTableCornerButton::section { background-color: %(raised)s; border: 1px solid %(edge_soft)s; }
""")

add("QHeaderView", """
QHeaderView { background-color: %(panel)s; border: none; }

QHeaderView::section { color: %(text)s; background-color: %(raised)s; border: 1px solid %(edge_soft)s; padding: 2px 4px 2px 4px; }
""")

add("QPlainTextEdit / QTextEdit", """
QTextEdit { color: %(text)s; background-color: %(field)s; border: 1px solid %(edge_soft)s; }

/* Script Editor and command output: left dark on purpose, see palette notes. */
QPlainTextEdit { color: %(script_text)s; background-color: %(script_bg)s; border: 1px solid %(edge)s; selection-color: %(hilite_text)s; selection-background-color: %(hilite)s; }

QPlainTextEdit:!editable { background-color: %(script_bg)s; }
""")

add("QGroupBox", """
QGroupBox { background-color: %(panel)s; border: 1px solid %(edge_soft)s; margin-top: 8px; padding-top: 8px; }

QGroupBox::title { subcontrol-origin: margin; left: 8px; padding: 0px 3px 0px 3px; background-color: %(panel)s; color: %(text)s; }
""")

add("QProgressBar", """
QProgressBar { color: %(text)s; background-color: %(field)s; border: 1px solid %(edge)s; text-align: center; }

QProgressBar::chunk { background-color: %(hilite)s; }
""")

add("QToolTip", """
QToolTip { color: %(text)s; background-color: %(tip)s; border: 1px solid %(text)s; padding: 2px; }
""")

add("QStatusBar", """
QStatusBar { color: %(text)s; background-color: %(panel)s; }

QStatusBar::item { border: none; }
""")

add("QSplitter", """
QSplitter::handle { background-color: %(tab_off)s; }

QSplitter::handle:hover { background-color: %(hilite)s; }
""")

add("QMessageBox / QFileDialog", """
QMessageBox, QFileDialog, QDialog { color: %(text)s; background-color: %(panel)s; }

QMessageBox QPushButton { min-width: 80px; min-height: 20px; }
""")

add("QmayaSeparator", """
QmayaSeparator { background-color: %(edge_soft)s; }
""")

add("Icon bars", """
/* Status line, shelf, tool box, panel toolbars and the time/range sliders. */
""" + bars("") + ",\n" + bars(" QWidget") + """ { background-color: %(chrome)s; }

""" + bars(" QLabel") + """ { background-color: transparent; }

""" + bars(" QPushButton") + ",\n" + bars(" QToolButton") + """ { background-color: %(chrome)s; border: none; }

""" + bars(" QPushButton:hover") + ",\n" + bars(" QToolButton:hover") + """ { background-color: %(chrome_hover)s; }

""" + bars(" QPushButton:pressed") + ",\n" + bars(" QPushButton:checked") + ",\n"
    + bars(" QToolButton:pressed") + ",\n" + bars(" QToolButton:checked") + """ { background-color: %(chrome_down)s; }

""" + bars(" QLineEdit") + """ { background-color: %(field)s; }

""" + bars(" QComboBox") + """ { background-color: %(btn_bottom)s; }

""" + bars(" QMenu") + ",\n" + bars(" QMenu QWidget") + """ { background-color: %(panel)s; }
""")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "Mayalight_stylesheet.qss")
with open(out, "w") as f:
    f.write("\n\n\n".join(SECTIONS) + "\n")
print("Wrote", out)
